package com.kinhiro.hostility.mixin.common;

import com.kinhiro.hostility.api.mixin.Targetable;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityTypes;
import net.minecraft.world.entity.monster.warden.Warden;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(Warden.class)
public abstract class TargetingWarden {
    @Inject(method = "canTargetEntity", at = @At("HEAD"), cancellable = true)
    private void hostility_staff$canTargetEntity(Entity entity, CallbackInfoReturnable<Boolean> cir) {
        if (((Targetable) this).hostility_staff$targeting() && entity != null && entity.getType() == EntityTypes.WARDEN)
            cir.setReturnValue(true);
    }
}
