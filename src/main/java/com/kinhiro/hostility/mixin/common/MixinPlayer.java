package com.kinhiro.hostility.mixin.common;

import com.kinhiro.hostility.common.item.HostilityStaffItem;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.player.Player;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(Player.class)
public abstract class MixinPlayer {
    @Inject(method = "attack", at = @At("HEAD"), cancellable = true)
    private void hostility_staff$attack(final Entity entity, CallbackInfo ci) {
        final var player = (Player) (Object) this;
        final var stack = player.getMainHandItem();
        if (!stack.isEmpty()
            && stack.getItem() instanceof final HostilityStaffItem item
            && item.onLeftClickEntity(stack, player, entity)) ci.cancel();
    }
}
