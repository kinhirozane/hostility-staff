package com.kinhiro.hostility.mixin.common;

import net.minecraft.world.entity.AgeableMob;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.monster.cubemob.AbstractCubeMob;
import net.minecraft.world.level.Level;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(AbstractCubeMob.class)
public abstract class TargetingAbstractCubeMob extends AgeableMob {
    protected TargetingAbstractCubeMob(final EntityType<? extends AgeableMob> type, final Level level) {
        super(type, level);
    }

    @Shadow
    protected abstract boolean isDealsDamage();

    @Shadow
    protected abstract void dealDamage(LivingEntity target);

    @Inject(method = "push", at = @At("RETURN"))
    private void hostility_staff$push(Entity entity, CallbackInfo ci) {
        if (entity == getTarget() && isDealsDamage())
            dealDamage((LivingEntity) entity);
    }
}
